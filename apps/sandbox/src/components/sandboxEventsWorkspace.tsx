"use client";

import { useCallback, useEffect, useState } from "react";

import styles from "./sandboxWorkspace.module.css";
import { formatTimestamp, sandboxFetch, useSandboxContext } from "./useSandboxContext";

type Delivery = {
  readonly id: string;
  readonly webhookId: string;
  readonly eventId: string;
  readonly event: string;
  readonly status: string;
  readonly attempts: number;
  readonly lastHttpStatus: number | null;
  readonly lastErrorCode: string | null;
  readonly createdAt: string;
};

type SandboxEvent = {
  readonly id: string;
  readonly eventType: string;
  readonly aggregateId: string;
  readonly createdAt: string;
};

export function SandboxEventsWorkspace() {
  const ctx = useSandboxContext();
  const [deliveries, setDeliveries] = useState<Delivery[]>([]);
  const [events, setEvents] = useState<SandboxEvent[]>([]);
  const [loading, setLoading] = useState(false);
  const [busyId, setBusyId] = useState("");
  const [error, setError] = useState("");
  const [notice, setNotice] = useState("");

  const loadData = useCallback(async (signal?: AbortSignal) => {
    if (!ctx.organizationId || !ctx.applicationId) { setDeliveries([]); setEvents([]); return; }
    setLoading(true); setError("");
    const qs = new URLSearchParams({ organizationId: ctx.organizationId, applicationId: ctx.applicationId });
    try {
      const [delRes, convRes] = await Promise.all([
        sandboxFetch<{ deliveries: Delivery[] }>(`/api/sandbox/events?${qs}`, { signal }),
        sandboxFetch<{ events: SandboxEvent[] }>(`/api/sandbox/conversations?${qs}`, { signal }).catch(() => ({ events: [] })),
      ]);
      if (!signal?.aborted) {
        setDeliveries(delRes.deliveries);
        setEvents(convRes.events);
      }
    } catch (cause) {
      if (!signal?.aborted) setError(cause instanceof Error ? cause.message : "Could not load webhook events.");
    } finally {
      if (!signal?.aborted) setLoading(false);
    }
  }, [ctx.organizationId, ctx.applicationId]);

  useEffect(() => {
    const controller = new AbortController();
    void loadData(controller.signal);
    return () => controller.abort();
  }, [loadData]);

  async function retryDelivery(delivery: Delivery) {
    if (!ctx.organizationId || !ctx.applicationId || busyId) return;
    setBusyId(delivery.id); setError(""); setNotice("");
    try {
      await sandboxFetch("/api/sandbox/events", {
        method: "POST",
        body: JSON.stringify({ organizationId: ctx.organizationId, applicationId: ctx.applicationId, webhookId: delivery.webhookId, deliveryId: delivery.id }),
      });
      setNotice(`Queued retry for delivery ${delivery.id}.`);
      await loadData();
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : "Retry failed.");
    } finally {
      setBusyId("");
    }
  }

  return (
    <section className={styles.page} aria-labelledby="events-title">
      <header className={styles.header}>
        <div>
          <p className={styles.eyebrow}>Sandbox <span aria-hidden="true">/</span> Webhook events</p>
          <h1 id="events-title">Webhook events</h1>
          <p>Inspect synthetic sandbox events and signed outbound webhook delivery attempts, including dead-letter retries.</p>
        </div>
        <div className={styles.selectors}>
          <label>
            Organization
            <select value={ctx.organizationId} onChange={(e) => ctx.setOrganizationId(e.target.value)} disabled={ctx.loadingOrgs || !ctx.organizations.length}>
              {ctx.organizations.map((o) => <option key={o.id} value={o.id}>{o.name}</option>)}
            </select>
          </label>
          <label>
            Application
            <select value={ctx.applicationId} onChange={(e) => ctx.setApplicationId(e.target.value)} disabled={!ctx.applications.length}>
              {ctx.applications.map((a) => <option key={a.id} value={a.id}>{a.name}</option>)}
            </select>
          </label>
        </div>
      </header>

      {(ctx.contextError || error) ? <p className={styles.error} role="alert">{ctx.contextError || error}</p> : null}
      {notice ? <p className={styles.notice} role="status">{notice}</p> : null}

      <section className={styles.panel} aria-label="Webhook deliveries">
        <div className={styles.panelHeading}>
          <div><h2>Signed webhook deliveries</h2><p>Delivery records generated by sandbox messaging and scenarios.</p></div>
          <button type="button" className={styles.secondaryBtn} disabled={loading || !ctx.applicationId} onClick={() => void loadData()}>Refresh</button>
        </div>
        {deliveries.length ? (
          <div className={styles.tableScroll}>
            <table>
              <thead><tr><th scope="col">Event</th><th scope="col">Status</th><th scope="col">Attempts</th><th scope="col">HTTP / Error</th><th scope="col">Created</th><th scope="col">Action</th></tr></thead>
              <tbody>
                {deliveries.map((d) => (
                  <tr key={d.id}>
                    <td><code>{d.event}</code></td>
                    <td><code>{d.status}</code></td>
                    <td>{d.attempts}</td>
                    <td>{d.lastHttpStatus ?? d.lastErrorCode ?? "—"}</td>
                    <td>{formatTimestamp(d.createdAt)}</td>
                    <td><button type="button" className={styles.secondaryBtn} disabled={busyId === d.id || d.status === "delivered"} onClick={() => void retryDelivery(d)}>Retry</button></td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        ) : (
          <p className={styles.empty}>{loading ? "Loading webhook deliveries..." : "No webhook deliveries recorded yet."}</p>
        )}
      </section>

      <section className={styles.panel} aria-label="Synthetic events">
        <div className={styles.panelHeading}><div><h2>Synthetic sandbox event stream</h2><p>Newest 50 events emitted inside this sandbox application.</p></div></div>
        {events.length ? (
          <div className={styles.tableScroll}>
            <table>
              <thead><tr><th scope="col">Event ID</th><th scope="col">Type</th><th scope="col">Aggregate ID</th><th scope="col">Recorded</th></tr></thead>
              <tbody>
                {events.map((ev) => (
                  <tr key={ev.id}>
                    <td><code>{ev.id}</code></td>
                    <td><code>{ev.eventType}</code></td>
                    <td><code>{ev.aggregateId}</code></td>
                    <td>{formatTimestamp(ev.createdAt)}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        ) : (
          <p className={styles.empty}>{loading ? "Loading synthetic events..." : "No synthetic events recorded yet."}</p>
        )}
      </section>
    </section>
  );
}
